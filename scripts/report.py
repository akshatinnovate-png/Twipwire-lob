def replay_payload(s, title, change_points=(), t_live=0, n_points=2400):
    y = np.asarray(s["y"])
    T = len(y)
    k = max(1, T // n_points)
    idx = np.arange(0, T, k)
    def ds(a, w=None):
        a = np.asarray(a, dtype=float)
        if w:
            a = _rolling(a, w)
        return [None if not np.isfinite(v) else round(float(v), 4) for v in a[idx]]
    w = max(1000, 4 * k)
    se = lambda pred: (y - np.asarray(pred)) ** 2 if pred is not None else None
    out = dict(title=title, n=int(T), step=int(k), t_live=int(t_live),
               change_points=[int(c) for c in change_points],
               y=ds(y, max(5, k)), yhat=ds(s["yhat"], max(5, k)), q=ds(s["q"]),
               logR_f=ds(s["logR_f"]), logR_r=ds(s["logR_r"]),
               mse_tw=ds(se(s["yhat"]), w), mse_b1=ds(se(s["b1"]), w) if s.get("b1") is not None else None,
               mse_b4=ds(se(s["b4"]), w) if s.get("b4") is not None else None,
               coverage=ds((np.abs(y - np.asarray(s["yhat"])) <= np.asarray(s["q"])).astype(float), w),
               call_rate=ds((np.asarray(s["calls"]) != 0).astype(float), w),
               weights=[[round(float(v), 3) for v in row] for row in np.asarray(s["weights"])[idx]],
               alarms_f=[int(a) for a in s["alarms_f"]], alarms_r=[int(a) for a in s["alarms_r"]],
               b3_alarms=[int(a) for a in s.get("b3_alarms", [])])
    if "time" in s:
        tm = np.asarray(s["time"])[: T]
        out["clock"] = [round(float((v - 34200) / 3600 + 9.5), 3) for v in tm[idx]]
    return out


