def _style(plt):
    plt.rcParams.update({
        "figure.facecolor": PINK, "axes.facecolor": PAPER, "axes.edgecolor": INK,
        "axes.labelcolor": INK, "xtick.color": INK, "ytick.color": INK, "text.color": INK,
        "font.family": "monospace", "font.size": 9, "axes.grid": True, "grid.color": "#e3c9cf",
        "grid.linewidth": 0.5, "axes.titleweight": "bold", "axes.titlelocation": "left",
    })


def _rolling(x, w):
    c = np.cumsum(np.r_[0, x])
    out = np.full(len(x), np.nan)
    out[w - 1:] = (c[w:] - c[:-w]) / w
    return out


